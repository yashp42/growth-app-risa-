        rc, st, vis, note = classify(rel)
        entries.append(((dataset_id(rel), Path(rel).stem.replace("_", " "), rel, None, rc, st, vis, len(rows), json.dumps(cols), sha(p), note or None, "IB-REF-LIBRARY"), rows))
