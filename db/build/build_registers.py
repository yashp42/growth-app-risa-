        for ws in wb.worksheets:
            hdr, rows = sheet_rows(ws)
            entries.append(((dataset_id(rel, ws.title), f"{Path(rel).stem} · {ws.title}", rel, ws.title, rc, st, vis_fn(ws.title), len(rows), json.dumps(hdr),
                             sha(REPO / rel), note, "IB-REF-LIBRARY"), rows))
